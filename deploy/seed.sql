-- Очистка перед наполнением: замеры должны стартовать
-- с воспроизводимого состояния.
TRUNCATE parts, categories RESTART IDENTITY CASCADE;

INSERT INTO categories (name) VALUES
  ('Крепёж'), ('Подшипники'), ('Уплотнения'),
  ('Валы'), ('Втулки'), ('Шестерни'),
  ('Пружины'), ('Прокладки');

INSERT INTO parts (
    category_id, name, article, size, material,
    weight_g, description
)
SELECT
    (SELECT id FROM categories OFFSET (i % 8) LIMIT 1),
    'Деталь ' || (ARRAY['Болт','Гайка','Шайба','Втулка','Вал',
                        'Шестерня','Пружина','Прокладка'])[1 + (i % 8)]
        || ' ' || (10 + i % 90) || 'x' || (20 + i % 60),
    'ART-' || LPAD(i::text, 7, '0'),
    (10 + i % 90) || 'x' || (20 + i % 60) || 'x' || (5 + i % 25),
    (ARRAY['Сталь 40Х','Сталь 45','ШХ15','Латунь Л63',
           'Бронза БрАЖ','Чугун СЧ20','Алюминий Д16',
           'Нержавейка 12Х18Н10Т'])[1 + (i % 8)],
    10 + (i * 7) % 4990,
    'Деталь общего назначения, партия ' || (i % 500)
        || ', технические условия по ГОСТ ' || (1000 + i % 9000)
        || '-' || (1970 + i % 55) || '. Применяется в узлах '
        || 'общепромышленного оборудования.'
FROM generate_series(1, :n) AS i;

ANALYZE parts;
